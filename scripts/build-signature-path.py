"""Builds src/data/signaturePath.ts: "Ryan DeBoer" in Caveat 500 as real cubic Bezier
outlines, plus every on-curve anchor with its incoming and outgoing handles and its
distance along the path. The hero's signature write-on draws this path and shows the
anchors where they actually are, the way the pen tool shows a path being drawn.

Replace the text with a traced signature later by swapping the outline source; the
data shape stays the same.

Run (fontTools required):  python build-signature-path.py <Caveat[wght].ttf>
"""
import json, math, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.basePen import BasePen

TEXT, WEIGHT, SIZE, X0, BASE = 'Ryan DeBoer', 500, 34, 2, 34
OUT = Path(__file__).resolve().parents[1] / 'src/data/signaturePath.ts'

font = instantiateVariableFont(TTFont(sys.argv[1]), {'wght': WEIGHT})
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
upem = font['head'].unitsPerEm
k = SIZE / upem

def bez(p0, p1, p2, p3, t):
    u = 1 - t
    return tuple(u**3 * a + 3 * u * u * t * b + 3 * u * t * t * c + t**3 * d for a, b, c, d in zip(p0, p1, p2, p3))

def seg_len(p0, p1, p2, p3, n=24):
    pts = [bez(p0, p1, p2, p3, i / n) for i in range(n + 1)]
    return sum(math.dist(a, b) for a, b in zip(pts, pts[1:]))

class Collect(BasePen):
    """Every segment as a cubic in SVG space, with the anchors in drawing order."""
    def __init__(self, gs, dx):
        super().__init__(gs); self.dx = dx; self.segs = []; self.start = None
    def tx(self, p): return (round(X0 + (self.dx + p[0]) * k, 2), round(BASE - p[1] * k, 2))
    def _moveTo(self, p): self.cur = self.start = self.tx(p); self.segs.append(('M', self.cur))
    def _lineTo(self, p):
        q = self.tx(p); a = self.cur
        self.segs.append(('C', (a, (a[0] + (q[0] - a[0]) / 3, a[1] + (q[1] - a[1]) / 3), (a[0] + 2 * (q[0] - a[0]) / 3, a[1] + 2 * (q[1] - a[1]) / 3), q), True))
        self.cur = q
    def _curveToOne(self, p1, p2, p3):
        a = self.cur; b, c, d = self.tx(p1), self.tx(p2), self.tx(p3)
        self.segs.append(('C', (a, b, c, d), False)); self.cur = d
    def _qCurveToOne(self, p1, p2):
        a = self.cur; q1, q2 = self.tx(p1), self.tx(p2)
        b = (a[0] + 2 / 3 * (q1[0] - a[0]), a[1] + 2 / 3 * (q1[1] - a[1]))
        c = (q2[0] + 2 / 3 * (q1[0] - q2[0]), q2[1] + 2 / 3 * (q1[1] - q2[1]))
        self.segs.append(('C', (a, b, c, q2), False)); self.cur = q2
    def _closePath(self):
        if self.cur and self.start and self.cur != self.start: self._lineTo_svg(self.start)
        self.segs.append(('Z',))
    def _lineTo_svg(self, q):
        a = self.cur
        self.segs.append(('C', (a, (a[0] + (q[0] - a[0]) / 3, a[1] + (q[1] - a[1]) / 3), (a[0] + 2 * (q[0] - a[0]) / 3, a[1] + 2 * (q[1] - a[1]) / 3), q), True))
        self.cur = q
    _endPath = _closePath

hmtx = font['hmtx'].metrics
segs, dx = [], 0
for ch in TEXT:
    name = cmap[ord(ch)]
    pen = Collect(glyphs, dx); glyphs[name].draw(pen); segs += pen.segs
    dx += hmtx[name][0]

f = lambda v: f'{v:.2f}'.rstrip('0').rstrip('.')
d, anchors, total, pending_in = [], [], 0.0, None
for s in segs:
    if s[0] == 'M':
        d.append(f'M{f(s[1][0])} {f(s[1][1])}')
        anchors.append(dict(x=s[1][0], y=s[1][1], at=round(total, 2), hin=None, hout=None, contour=True))
    elif s[0] == 'C':
        a, b, c, e = s[1]; straight = s[2]
        d.append('C' + ' '.join(f'{f(p[0])} {f(p[1])}' for p in (b, c, e)))
        if not straight and anchors: anchors[-1]['hout'] = [round(b[0], 2), round(b[1], 2)]
        total += seg_len(a, b, c, e)
        anchors.append(dict(x=e[0], y=e[1], at=round(total, 2), hin=None if straight else [round(c[0], 2), round(c[1], 2)], hout=None, contour=False))
    else:
        d.append('Z')

OUT.write_text(
    '// Generated by scripts/build-signature-path.py from Caveat 500. Do not edit by hand.\n'
    '// The real outline of the hero signature plus every anchor, its handles, and its\n'
    '// distance along the path, for the pen-tool write-on.\n'
    'export interface SignatureAnchor { x: number; y: number; at: number; hin: [number, number] | null; hout: [number, number] | null; contour: boolean; }\n'
    f'export const SIGNATURE_D = {json.dumps("".join(d))};\n'
    f'export const SIGNATURE_LENGTH = {round(total, 2)};\n'
    f'export const SIGNATURE_WIDTH = {round(X0 + dx * k + 2, 1)};\n'
    f'export const SIGNATURE_ANCHORS: SignatureAnchor[] = {json.dumps(anchors, separators=(",", ":"))};\n')
print(OUT, 'length', round(total, 1), 'anchors', len(anchors), 'width', round(X0 + dx * k, 1))
