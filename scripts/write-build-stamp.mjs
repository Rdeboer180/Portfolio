#!/usr/bin/env node
// Writes src/data/build.ts from the current git HEAD so Page Properties can
// show a real "last modified" instead of a guessed one. Runs before start,
// build and test. The output is gitignored: committing it would leave it one
// commit stale forever and dirty the tree on every start.
import { execFileSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';

const out = new URL('../src/data/build.ts', import.meta.url);

try {
  const [sha, date, author] = execFileSync('git', ['log', '-1', '--format=%H%n%cI%n%an'], { encoding: 'utf8' }).trim().split('\n');
  const body = [
    '// Generated by scripts/write-build-stamp.mjs on every start and build. Do not edit.',
    'export const BUILD = {',
    `  sha: '${sha}',`,
    `  shortSha: '${sha.slice(0, 7)}',`,
    `  date: '${date}',`,
    `  author: '${author.replace(/'/g, "\\'")}',`,
    '} as const;',
    '',
  ].join('\n');
  writeFileSync(out, body);
  console.log(`build stamp: ${sha.slice(0, 7)} ${date}`);
} catch {
  if (existsSync(out)) {
    console.warn('build stamp: git unavailable, keeping the existing src/data/build.ts');
  } else {
    // No repository (a tarball build, say). Say so rather than invent a commit.
    writeFileSync(out, [
      '// Generated by scripts/write-build-stamp.mjs without git. Do not edit.',
      'export const BUILD = {',
      "  sha: 'unversioned',",
      "  shortSha: 'unversioned',",
      `  date: '${new Date().toISOString()}',`,
      "  author: 'Ryan DeBoer',",
      '} as const;',
      '',
    ].join('\n'));
    console.warn('build stamp: git unavailable, wrote an unversioned stamp');
  }
}
